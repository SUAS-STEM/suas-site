import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const projectRoot = process.cwd();
const galleryDirectory = path.join(projectRoot, "public", "images", "gallery");
const thumbnailDirectory = path.join(galleryDirectory, "thumbs");
const outputFile = path.join(projectRoot, "lib", "galleryPhotos.generated.ts");
const supportedExtensions = new Set([".gif", ".jpeg", ".jpg", ".png", ".svg", ".webp"]);

// Immutable snapshot containing all current gallery originals. Cloudflare is
// still the primary source; this snapshot is used only if the Pi/tunnel cannot
// satisfy a cache miss.
const durableGalleryBase =
    "https://raw.githubusercontent.com/SUAS-STEM/suas-site/75425f3bafba710b7d8a1b974ac7cab36d44622f/public/images/gallery";

const photoNames = fs
    .readdirSync(galleryDirectory, { withFileTypes: true })
    .filter((entry) => entry.isFile())
    .filter((entry) => supportedExtensions.has(path.extname(entry.name).toLowerCase()))
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b));

fs.mkdirSync(thumbnailDirectory, { recursive: true });

// Keep multi-megabyte camera originals for fullscreen viewing, but give the
// initial grid small WebP assets so a page visit does not download all of the
// originals. These files are generated during every build and ignored by git.
await Promise.all(
    photoNames.map(async (fileName) => {
        const thumbnailName = `${fileName.replace(/\.[^.]+$/, "")}.webp`;
        await sharp(path.join(galleryDirectory, fileName))
            .resize({ width: 800, withoutEnlargement: true })
            .webp({ quality: 72 })
            .toFile(path.join(thumbnailDirectory, thumbnailName));
    }),
);

const photos = photoNames.map((fileName) => `/images/gallery/${encodeURIComponent(fileName)}`);
const thumbnails = photoNames.map(
    (fileName) =>
        `/images/gallery/thumbs/${encodeURIComponent(fileName.replace(/\.[^.]+$/, ""))}.webp`,
);

const contents =
    `// Generated by scripts/generate-gallery-manifest.mjs. Do not edit manually.\n` +
    `export const DURABLE_GALLERY_BASE = ${JSON.stringify(durableGalleryBase)};\n` +
    `export const GALLERY_PHOTOS = ${JSON.stringify(photos, null, 4)} as const;\n` +
    `export const GALLERY_THUMBNAILS = ${JSON.stringify(thumbnails, null, 4)} as const;\n`;

fs.writeFileSync(outputFile, contents, "utf8");
