import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import sharp from "sharp";

const projectRoot = process.cwd();
const galleryDirectory = path.join(projectRoot, "public", "images", "gallery");
const thumbnailDirectory = path.join(galleryDirectory, "thumbs");
const displayDirectory = path.join(galleryDirectory, "display");
const outputFile = path.join(projectRoot, "lib", "galleryPhotos.generated.ts");
const supportedExtensions = new Set([".gif", ".jpeg", ".jpg", ".png", ".svg", ".webp"]);

// Immutable snapshot containing all current gallery originals. Cloudflare is
// still the primary source; this snapshot is used only if the Pi/tunnel cannot
// satisfy a cache miss.
const durableGalleryBase =
    "https://raw.githubusercontent.com/SUAS-STEM/suas-site/75425f3bafba710b7d8a1b974ac7cab36d44622f/public/images/gallery";

const photoNames = fs
    .readdirSync(galleryDirectory, { withFileTypes: true })
    .filter((entry) => entry.isFile())
    .filter((entry) => supportedExtensions.has(path.extname(entry.name).toLowerCase()))
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b));

fs.mkdirSync(thumbnailDirectory, { recursive: true });
fs.mkdirSync(displayDirectory, { recursive: true });

// Build derivatives from content-addressed names. Unchanged images keep the
// same URL across deploys, while replacing an original automatically produces
// a new URL that is safe to cache as immutable at the browser and CDN.
const derivatives = photoNames.map((fileName) => {
    const input = path.join(galleryDirectory, fileName);
    const hash = createHash("sha256").update(fs.readFileSync(input)).digest("hex").slice(0, 12);
    const stem = fileName.replace(/\.[^.]+$/, "");
    return {
        fileName,
        input,
        thumbnailName: `${stem}.${hash}.webp`,
        displayName: `${stem}.${hash}.webp`,
    };
});

// The page never needs multi-megabyte camera originals for normal viewing.
// Generate small grid thumbnails plus a high-quality 1600px display tier.
// Keep originals only as the durable/fallback source.
const queue = [...derivatives];
const workers = Array.from({ length: Math.min(4, queue.length) }, async () => {
    while (queue.length > 0) {
        const item = queue.shift();
        if (!item) return;
        await sharp(item.input)
            .rotate()
            .resize({ width: 800, withoutEnlargement: true })
            .webp({ quality: 72 })
            .toFile(path.join(thumbnailDirectory, item.thumbnailName));
        await sharp(item.input)
            .rotate()
            .resize({ width: 1600, withoutEnlargement: true })
            .webp({ quality: 80 })
            .toFile(path.join(displayDirectory, item.displayName));
    }
});
await Promise.all(workers);

const photos = photoNames.map((fileName) => `/images/gallery/${encodeURIComponent(fileName)}`);
const thumbnails = derivatives.map(
    ({ thumbnailName }) => `/images/gallery/thumbs/${encodeURIComponent(thumbnailName)}`,
);
const displayPhotos = derivatives.map(
    ({ displayName }) => `/images/gallery/display/${encodeURIComponent(displayName)}`,
);

const contents =
    `// Generated by scripts/generate-gallery-manifest.mjs. Do not edit manually.\n` +
    `export const DURABLE_GALLERY_BASE = ${JSON.stringify(durableGalleryBase)};\n` +
    `export const GALLERY_PHOTOS = ${JSON.stringify(photos, null, 4)} as const;\n` +
    `export const GALLERY_DISPLAY = ${JSON.stringify(displayPhotos, null, 4)} as const;\n` +
    `export const GALLERY_THUMBNAILS = ${JSON.stringify(thumbnails, null, 4)} as const;\n`;

fs.writeFileSync(outputFile, contents, "utf8");
