import fs from "node:fs/promises";
import path from "node:path";
import { createHash } from "node:crypto";
import sharp from "sharp";

const root = process.cwd();
const originals = path.join(root, "public", "images", "members");
const derivatives = path.join(originals, "optimized");
const manifestPath = path.join(root, "lib", "memberPhotos.generated.ts");
const widths = [256, 640];

await fs.mkdir(derivatives, { recursive: true });
const files = (await fs.readdir(originals))
    .filter((file) => file.toLowerCase().endsWith(".png"))
    .sort();
const images = {};
const queue = [...files];

// This runs during build, never on image requests. Keep the Pi responsive.
async function worker() {
    while (queue.length) {
        const file = queue.shift();
        if (!file) return;
        const input = path.join(originals, file);
        const hash = createHash("sha256")
            .update(await fs.readFile(input))
            .digest("hex")
            .slice(0, 12);
        const stem = file.slice(0, -4);
        const urls = [];

        for (const width of widths) {
            const filename = `${stem}.${hash}.${width}.webp`;
            const dest = path.join(derivatives, filename);
            try {
                await fs.access(dest);
            } catch {
                await sharp(input)
                    .rotate()
                    .resize({ width, withoutEnlargement: true })
                    .webp({ quality: 78, effort: 4 })
                    .toFile(dest);
            }
            const stats = await fs.stat(dest);
            if (stats.size === 0 || stats.size > 256 * 1024) {
                throw new Error(`Unexpected ${width}px member image size: ${file} (${stats.size} bytes)`);
            }
            urls.push(`/images/members/optimized/${encodeURIComponent(filename)}`);
        }
        images[file] = { small: urls[0], large: urls[1] };
    }
}

await Promise.all(Array.from({ length: Math.min(2, queue.length) }, worker));

const manifest = `// Generated by scripts/generate-member-images.mjs; do not edit.\n` +
    `// Paths are content-addressed so browsers and CDNs never reuse a stale portrait.\n` +
    `export const MEMBER_IMAGES: Record<string, { small: string; large: string }> = ${JSON.stringify(
        Object.fromEntries(Object.entries(images).sort(([a], [b]) => a.localeCompare(b))),
        null,
        4,
    )};\n`;

if ((await fs.readFile(manifestPath, "utf8").catch(() => "")) !== manifest) {
    await fs.writeFile(manifestPath, manifest);
}
console.log(`Generated/verified ${files.length} team portraits at ${widths.join("/")}px.`);
